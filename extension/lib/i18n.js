	let current = "en";

	function detect(list) {
		const nav = globalThis.navigator;
		const prefs = list || nav?.languages || [nav?.language || "en"];
		for (const raw of prefs) {
			const base = String(raw || "").toLowerCase().split(/[-_]/)[0];
			const code = base === "in" ? "id" : base;
			if (STRINGS[code]) return code;
		}
		return "en";
	}

	function resolve(setting) {
		return setting && setting !== "auto" && STRINGS[setting] ? setting : detect();
	}

	function setLang(setting) {
		current = resolve(setting);
		return current;
	}

	function raw(key) {
		return STRINGS[current]?.[key] ?? STRINGS.en[key] ?? key;
	}

	function t(key, vars) {
		const s = raw(key);
		return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
	}

	function rich(key, vars = {}) {
		const s = raw(key);
		const out = [];
		let last = 0;
		for (const m of s.matchAll(/\{(\w+)\}/g)) {
			out.push(s.slice(last, m.index));
			out.push(m[1] in vars ? vars[m[1]] : m[0]);
			last = m.index + m[0].length;
		}
		out.push(s.slice(last));
		return out.filter((x) => x !== "" && x != null);
	}

	function locale(code = current) {
		return LOCALES[code] || code;
	}

	function num(n) {
		try {
			return new Intl.NumberFormat(locale()).format(n);
		} catch {
			return String(n);
		}
	}

	function nameOf(code) {
		return LANGS.find(([c]) => c === code)?.[1] || code;
	}

	YTSE.i18n = {
		LANGS,
		STRINGS,
		detect,
		resolve,
		setLang,
		getLang: () => current,
		dir: () => (RTL.has(current) ? "rtl" : "ltr"),
		locale,
		t,
		rich,
		num,
		nameOf,
	};
